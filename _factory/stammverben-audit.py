#!/usr/bin/env python3
"""
stammverben-audit.py — Session 41 (PRD_Stammverben_Audit.md)

Makes data/verbs.json obey one rule:
  Stammverben = verbs that are NOT prefix + independent base verb.

Two steps, both idempotent:

1. Restore Session 13 (2026-06-07). That audit was applied only to js/data.js and
   never to verbs.json, so Wörter Intake #1 rebuilt over it. Source of truth for
   what it decided: _factory/s13-verbs-snapshot.json (verbs from the pre-intake
   bundle backup). 14 base roots come back; 23 prefixed "roots" become variants
   (4 of them were duplicates of an existing variant entry).

2. Classify every remaining root by de.wiktionary.org's rendered Herkunft
   (_factory/stammverben/wiktionary-herkunft.tsv). A root is PREFIXED when the
   Herkunft states it is formed from "dem Verb X" / "zum Verb X" / "vom Verb X",
   X == word minus a prefix, AND X has at least one living (non-"veraltet") verb
   sense (_factory/stammverben/wiktionary-bases.tsv). Derivations from a noun or
   adjective (betonen < Ton, erledigen < ledig) and from obsolete verbs
   (gewinnen < winnen, verpflichten < pflichten) stay roots.
     - base is a root in the app  -> moved under it as a prefix_variant
     - base is not                -> stays in the list, flagged
                                     "standalone_variant": true (served under
                                     Variationen, no root unlock needed)

Writes data/verbs.json and _factory/stammverben/audit-report.md.
Run: python3 _factory/stammverben-audit.py  then  python3 _factory/bundle-data.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERBS = ROOT / "data" / "verbs.json"
SNAP = ROOT / "_factory" / "s13-verbs-snapshot.json"
SV = ROOT / "_factory" / "stammverben"

S13_BASES = ["fassen", "heben", "bieten", "schlagen", "wählen", "nutzen", "fordern",
             "scheinen", "deuten", "wirken", "lehnen", "weisen", "gleichen", "meiden"]
S13_DUPLICATES = ["verb_gehören", "verb_versuchen", "verb_beschreiben", "verb_anerkennen"]
S13_EXTRA = {"verb_versprechen": "verb_sprechen", "verb_widersprechen": "verb_sprechen",
             "verb_umgehen": "verb_gehen"}

VARIANT_KEYS = ("id", "prefix", "word", "english", "separable", "notes")


def as_variant(root_entry, s13_variant):
    """Variant in the shape the app already uses; facts from the current root entry,
    prefix/separability/notes from the Session 13 decision."""
    v = {
        "id": root_entry["id"],
        "prefix": s13_variant["prefix"],
        "word": root_entry["root"],
        "english": root_entry["english"],
        "separable": s13_variant["separable"],
        "notes": s13_variant.get("notes", ""),
    }
    cases = (root_entry.get("grammar") or {}).get("case_requirements")
    if cases is not None:
        v["grammar"] = {"case_requirements": cases}
    return v


def load_tsv(p):
    rows = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        rows[parts[0]] = parts[1:]
    return rows


def main():
    verbs = json.loads(VERBS.read_text(encoding="utf-8"))
    snap = {v["id"]: v for v in json.loads(SNAP.read_text(encoding="utf-8"))}
    by_id = {v["id"]: v for v in verbs}
    report = ["# Stammverben audit — Session 41", "",
              "Generated by `_factory/stammverben-audit.py`. Do not edit by hand.", ""]

    # ── 1. Session 13 restore ────────────────────────────────────────────────
    s13_var = {}
    for v in snap.values():
        for pv in v.get("prefix_variants") or []:
            s13_var[pv["id"]] = (v["id"], pv)

    report += ["## 1. Session 13 restored", ""]
    for b in S13_BASES:
        bid = "verb_" + b
        if bid in by_id:
            continue
        base = json.loads(json.dumps(snap[bid]))
        base["conjugation"].pop("prateritum", None)     # current root shape
        new_variants = []
        for pv in base["prefix_variants"]:
            cur = by_id.get(pv["id"])
            new_variants.append(as_variant(cur, pv) if cur else pv)
        base["prefix_variants"] = new_variants
        verbs.append(base)
        by_id[bid] = base
        report.append(f"- restored root **{b}** with " +
                      ", ".join(p["word"] for p in new_variants))

    for vid, parent in S13_EXTRA.items():
        if vid in by_id and not by_id[vid].get("standalone_variant"):
            par = by_id[parent]
            if not any(p["id"] == vid for p in par["prefix_variants"]):
                par["prefix_variants"].append(as_variant(by_id[vid], s13_var[vid][1]))
            report.append(f"- {by_id[vid]['root']} → variant of {par['root']}")

    moved = set(S13_DUPLICATES) | set(S13_EXTRA)
    for b in S13_BASES:
        moved |= {p["id"] for p in by_id["verb_" + b]["prefix_variants"]}
    for vid in S13_DUPLICATES:
        if vid in by_id:
            report.append(f"- removed duplicate root {by_id[vid]['root']} (already a variant)")
    # A demoted root's own variants follow it into its new family, keeping their own
    # prefix (angehören: an- on gehören, now filed in the hören family).
    for vid in moved:
        if vid not in by_id:
            continue
        kids = by_id[vid].get("prefix_variants") or []
        if not kids:
            continue
        family = next((v for v in by_id.values() if v["id"] not in moved and
                       any(p["id"] == vid for p in v.get("prefix_variants") or [])), None)
        assert family, f"no family for demoted root {vid} with variants"
        for k in kids:
            if not any(p["id"] == k["id"] for p in family["prefix_variants"]):
                family["prefix_variants"].append(k)
            report.append(f"- {k['word']} (variant of demoted {by_id[vid]['root']}) → {family['root']} family")
    verbs = [v for v in verbs if v["id"] not in moved]
    by_id = {v["id"]: v for v in verbs}

    # ── 2. Wiktionary classification ────────────────────────────────────────
    herkunft = load_tsv(SV / "wiktionary-herkunft.tsv")
    bases = load_tsv(SV / "wiktionary-bases.tsv")
    root_by_word = {v["root"]: v for v in verbs if not v.get("standalone_variant")}

    report += ["", "## 2. Remaining prefixed roots (de.wiktionary.org Herkunft)", "",
               "| verb | verdict | evidence |", "|---|---|---|"]
    to_drop = set()
    for v in verbs:
        word = v["root"]
        if word not in herkunft:
            continue
        text = herkunft[word][1] if len(herkunft[word]) > 1 else ""
        m = re.search(r"(?:dem|zum|vom) Verb (\w+)", text)
        verdict, base = "root", None
        if m and word.endswith(m.group(1)) and word != m.group(1):
            cand = m.group(1)
            senses, old = (int(x) for x in bases.get(cand, ["0", "0"])[:2])
            if senses - old > 0:
                base = cand
            else:
                verdict = f"root (base *{cand}* is obsolete)"
        if base:
            prefix = word[: -len(base)]
            separable = "Partikel" in text
            parent = root_by_word.get(base)
            if parent:
                if not any(p["id"] == v["id"] for p in parent["prefix_variants"]):
                    parent["prefix_variants"].append({
                        "id": v["id"], "prefix": prefix, "word": word,
                        "english": v["english"], "separable": separable,
                        "notes": "", "grammar": {"case_requirements":
                            (v.get("grammar") or {}).get("case_requirements", [])}})
                to_drop.add(v["id"])
                verdict = f"variant of {base}"
            else:
                v["standalone_variant"] = True
                v["prefix"] = prefix
                v["base"] = base
                v["separable"] = separable
                verdict = f"standalone variation ({prefix}- + {base}, base not in app)"
        ev = text if len(text) < 110 else text[:107] + "…"
        report.append(f"| {word} | {verdict} | {ev or '— no Herkunft on Wiktionary'} |")
    for v in verbs:
        # A standalone variation may keep variants of its own (entwickeln →
        # weiterentwickeln); the app gates them on the standalone being unlocked.
        if v["id"] in to_drop:
            assert not v.get("prefix_variants"), f"{v['root']} has variants of its own"
    verbs = [v for v in verbs if v["id"] not in to_drop]

    roots = [v for v in verbs if not v.get("standalone_variant")]
    stand = [v for v in verbs if v.get("standalone_variant")]
    nvar = sum(len(v.get("prefix_variants") or []) for v in verbs)
    report += ["", "## Totals", "",
               f"- Stammverben: **{len(roots)}**",
               f"- Variants under a root: **{nvar}**",
               f"- Standalone variations: **{len(stand)}**", ""]

    VERBS.write_text(json.dumps(verbs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (SV / "audit-report.md").write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report[-5:]))


if __name__ == "__main__":
    main()
