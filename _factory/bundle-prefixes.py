#!/usr/bin/env python3
"""
bundle-prefixes.py — writes js/prefixes-data.js

Bundles the three Vorsilben source files into a single window global so the
PWA works from file://, localhost and GitHub Pages without fetch().

  data/prefixes.json                        -> PREFIXES_DATA.prefixes
  data/exercises/exercises-prefixes.json    -> PREFIXES_DATA.exercises
  data/grammar/prefix-lessons.json          -> PREFIXES_DATA.lessons

Run after generate-prefixes.py and validate-prefixes.py.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "js" / "prefixes-data.js"

SOURCES = {
    "prefixes":  ROOT / "data" / "prefixes.json",
    "exercises": ROOT / "data" / "exercises" / "exercises-prefixes.json",
    "lessons":   ROOT / "data" / "grammar" / "prefix-lessons.json",
}


def main():
    payload = {k: json.loads(p.read_text(encoding="utf-8")) for k, p in SOURCES.items()}

    # Carry the module descriptor here rather than rebundling the 2.2 MB
    # js/data.js. app.js merges it into appData.modules on load, the same way
    # the listening module does.
    modules = json.loads((ROOT / "data" / "modules.json").read_text(encoding="utf-8"))
    mod = next((m for m in modules if m["id"] == "module_prefixes"), None)
    if mod is None:
        raise SystemExit("module_prefixes missing from data/modules.json")
    payload["module"] = mod

    header = (
        "/**\n"
        " * PREFIXES-DATA.JS — Bundled Vorsilben module data\n"
        " * Generated by _factory/bundle-prefixes.py — do not edit by hand.\n"
        " * Sources:\n"
        f" *   data/prefixes.json                       ({len(payload['prefixes'])} prefixes)\n"
        f" *   data/exercises/exercises-prefixes.json   ({len(payload['exercises'])} exercises)\n"
        f" *   data/grammar/prefix-lessons.json         ({len(payload['lessons'])} lessons)\n"
        " *\n"
        " * Validated by _factory/validate-prefixes.py — 0 integrity errors.\n"
        " */\n"
    )

    body = "window.PREFIXES_DATA = " + json.dumps(payload, ensure_ascii=False,
                                                  separators=(",", ":")) + ";\n"
    OUT.write_text(header + body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  ({OUT.stat().st_size / 1024:.0f} KB)")
    for k, v in payload.items():
        print(f"  {k:10s} {len(v) if isinstance(v, list) else 'ok'}")


if __name__ == "__main__":
    main()
